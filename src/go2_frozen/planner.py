"""Same bounded CEM command search with ideal or actual-policy rollout response.

The policy rollout is an exact-nominal-physics privileged baseline. It changes
commands only, never policy/model parameters. A response cannot improve except
through the actions generated by that frozen policy and the physical simulator.
"""
from __future__ import annotations
import time
import numpy as np
from .task import (advance_stage, nominal_command, running_cost, terminal_surrogate,
                   is_fallen, kinematic_step, feature)


class CommandMPC:
    def __init__(self, simulation, config, kind):
        self.config, self.kind = config, kind
        self.predictor = simulation.clone() if kind == "policy_rollout_mpc" else None
        self.rng = np.random.default_rng(config["planner"]["seed"])
        self.warm = np.zeros((config["planner"]["horizon"], 3))
        self.total_candidates = 0

    def _rollout(self, initial_state, snapshot, stage, residuals, fixed_command=None):
        cfg, state, cost = self.config, initial_state, 0.0
        if self.predictor is not None:
            self.predictor.restore(snapshot)
        first_command = first_feature = None
        for residual in residuals:
            stage = advance_stage(state, stage, cfg)
            command = np.clip(nominal_command(state, stage, cfg) + residual,
                              cfg["command_lower"], cfg["command_upper"])
            if fixed_command is not None:
                command = fixed_command
            if self.predictor is None:
                state = kinematic_step(state, command, cfg["macro_dt"])
                # Heading-aware nominal rectangle only: it is not a guaranteed
                # full-leg envelope. Final scoring uses actual full-body contact.
                c, s = abs(np.cos(state["yaw"])), abs(np.sin(state["yaw"]))
                footprint = np.array([c*.30+s*.20, s*.30+c*.20])
                for obstacle in cfg["obstacles"]:
                    if np.all(np.abs(state["position"][:2] - np.asarray(obstacle["pos"][:2]))
                              < np.asarray(obstacle["size"][:2]) + footprint):
                        cost += 1000.0
            else:
                step = self.predictor.step_command(command, cfg["macro_dt"], trace=False)
                state = step["state"]
                if step["obstacle_contacts"]:
                    cost += 1000.0
                if is_fallen(state, cfg):
                    cost += 1000.0
            if first_command is None:
                first_command, first_feature = command.copy(), feature(state)
            cost += cfg["macro_dt"] * running_cost(state, stage, cfg)
        return cost + terminal_surrogate(state, stage, cfg), first_command, first_feature

    def plan(self, simulation, stage):
        start = time.perf_counter()
        cfg, p = self.config, self.config["planner"]
        state = simulation.state()
        snapshot = simulation.snapshot() if self.predictor is not None else None
        mean = self.warm.copy()
        std = np.tile(p["residual_std"], (p["horizon"], 1))
        best = None
        nominal = nominal_command(state, stage, cfg)
        # Actual stop, turn-in-place and lateral correction are explicitly
        # evaluated within the same candidate budget, not merely permitted by bounds.
        fixed = {2: np.zeros(3), 3: np.array([0., 0., nominal[2]]),
                 4: np.array([0., nominal[1], nominal[2]])}
        for _ in range(p["iterations"]):
            candidates = self.rng.normal(mean, std, (p["candidates"], p["horizon"], 3))
            candidates[0] = 0.0  # unrestricted nominal feedback remains available
            candidates[1] = mean
            evaluated = [self._rollout(state, snapshot, stage, candidate, fixed.get(i))
                         for i, candidate in enumerate(candidates)]
            scores = np.array([v[0] for v in evaluated])
            indices = scores.argsort()
            if best is None or scores[indices[0]] < best[0]:
                i = indices[0]
                best = (*evaluated[i], np.zeros_like(mean) if i in fixed else candidates[i].copy())
            elite_indices = [i for i in indices if i not in fixed][:p["elites"]]
            elite = candidates[elite_indices]
            mean, std = elite.mean(0), np.maximum(elite.std(0), 0.02)
            self.total_candidates += len(candidates)
        self.warm = np.concatenate([best[3][1:], np.zeros((1, 3))])
        return {"command": best[1], "predicted_feature": best[2],
                "predicted_objective": float(best[0]), "wall_seconds": time.perf_counter()-start,
                "candidates": p["iterations"] * p["candidates"]}
