function modelFile = buildLearningPilotModel(outputDirectory, net, cfg, ...
    initialState, command, disturbance)
%BUILDLEARNINGPILOTMODEL Native discrete feedback graph, not an action replay.
%   From Workspace provides only command and unknown disturbance histories.
%   The actual simulated state feeds the frozen neural controller every dt.
%   Unit Delay carries all three physical states between the RK4 maps.
arguments
    outputDirectory (1,1) string
    net (1,1) struct
    cfg (1,1) struct
    initialState (3,1) single
    command (:,1) single
    disturbance (:,1) single
end
load_system('simulink');
modelName = 'learning_pilot_closed_loop';
if bdIsLoaded(modelName)
    modelName = ['learning_pilot_' char(datetime('now', 'Format', 'HHmmssSSS'))];
end
new_system(modelName);
dt = double(cfg.dt);
nSteps = numel(command);
sampleTime = sprintf('%.17g', dt);
set_param(modelName, 'Solver', 'FixedStepDiscrete', 'SolverType', 'Fixed-step', ...
    'FixedStep', sampleTime, 'StartTime', '0', ...
    'StopTime', sprintf('%.17g', (nSteps-1)*dt), ...
    'ReturnWorkspaceOutputs', 'on', 'SaveTime', 'on', 'TimeSaveName', 'tout', ...
    'SaveOutput', 'off', 'SignalLogging', 'off');
workspace = get_param(modelName, 'ModelWorkspace');
workspace.assignin('net', net);
workspace.assignin('cfg', cfg);
workspace.assignin('dt', dt);
workspace.assignin('initialState', initialState);
time = (0:nSteps-1)'*dt;
workspace.assignin('commandSeries', timeseries(command, time));
workspace.assignin('disturbanceSeries', timeseries(disturbance, time));

add_block('simulink/Sources/From Workspace', [modelName '/Held command'], ...
    'VariableName', 'commandSeries', 'Interpolate', 'off', ...
    'OutputAfterFinalValue', 'Holding final value', ...
    'SampleTime', sampleTime, 'Position', [30 25 145 55]);
add_block('simulink/Sources/From Workspace', [modelName '/Held disturbance'], ...
    'VariableName', 'disturbanceSeries', 'Interpolate', 'off', ...
    'OutputAfterFinalValue', 'Holding final value', ...
    'SampleTime', sampleTime, 'Position', [295 160 410 190]);
add_block('simulink/Discrete/Unit Delay', [modelName '/Actual physical state'], ...
    'InitialCondition', 'initialState', 'SampleTime', sampleTime, ...
    'Position', [30 85 145 125]);
add_block('simulink/User-Defined Functions/Level-2 MATLAB S-Function', ...
    [modelName '/Frozen full-action neural actor'], ...
    'FunctionName', 'learningPilotActorBlock', 'Parameters', 'net,dt', ...
    'Position', [210 55 390 110]);
add_block('simulink/User-Defined Functions/Level-2 MATLAB S-Function', ...
    [modelName '/Nonlinear actuator RK4'], ...
    'FunctionName', 'learningPilotPlantBlock', 'Parameters', 'cfg', ...
    'Position', [470 55 640 125]);
add_block('simulink/Sinks/To Workspace', [modelName '/Record actual action'], ...
    'VariableName', 'actionLog', 'SaveFormat', 'Array', ...
    'MaxDataPoints', 'inf', 'Position', [470 10 640 35]);
add_block('simulink/Sinks/To Workspace', [modelName '/Record next state'], ...
    'VariableName', 'stateLog', 'SaveFormat', 'Array', ...
    'MaxDataPoints', 'inf', 'Position', [710 75 835 110]);
add_line(modelName, 'Actual physical state/1', 'Frozen full-action neural actor/1', 'autorouting', 'on');
add_line(modelName, 'Held command/1', 'Frozen full-action neural actor/2', 'autorouting', 'on');
add_line(modelName, 'Actual physical state/1', 'Nonlinear actuator RK4/1', 'autorouting', 'on');
add_line(modelName, 'Frozen full-action neural actor/1', 'Nonlinear actuator RK4/2', 'autorouting', 'on');
add_line(modelName, 'Held disturbance/1', 'Nonlinear actuator RK4/3', 'autorouting', 'on');
add_line(modelName, 'Nonlinear actuator RK4/1', 'Actual physical state/1', 'autorouting', 'on');
add_line(modelName, 'Nonlinear actuator RK4/1', 'Record next state/1', 'autorouting', 'on');
add_line(modelName, 'Frozen full-action neural actor/1', 'Record actual action/1', 'autorouting', 'on');
annotation = Simulink.Annotation(modelName, ...
    ['Closed loop: actual state -> frozen neural actor -> actuator plant.' newline ...
     'Only high-level commands and disturbances are replayed; actions are recomputed.']);
annotation.Position = [185 220];
modelFile = fullfile(outputDirectory, modelName + ".slx");
save_system(modelName, modelFile);
end
