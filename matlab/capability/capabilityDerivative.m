function dx = capabilityDerivative(x,u,w,cfg)
%CAPABILITYDERIVATIVE Physical plant, not a fitted response surrogate.
dx = [x(3,:);x(4,:); ...
    (x(5,:)+x(6,:))/2-cfg.dv*x(3,:); ...
    (x(5,:)-x(6,:))/2-cfg.k*sin(x(2,:))-cfg.dr*x(4,:)+w; ...
    (-x(5,:)+u(1,:))/cfg.tau(1); ...
    (-x(6,:)+u(2,:))/cfg.tau(2)];
end
